class DiagnosticAnalysisDocument(BaseModel):
    """Canonical representation of a document in the diagnostic_analysis collection."""

    id: str = Field(
        default="",
        validation_alias=AliasChoices("_id", "analysis_id", "id"),
        description="Lowercase UUID v4 string",
    )
    analysis_id: str = Field(description="Lowercase UUID v4 string matching _id")
    student_id: str
    question_id: str
    attempt_data: Dict[str, Any]
    probe_loop_evidence: List[Dict[str, Any]] = Field(default_factory=list)
    student_parameters_snapshot: Union[StudentParametersSnapshot, Dict[str, Any]] = Field(
        default_factory=dict
    )
    intervention_and_language_output: Optional[Dict[str, Any]] = None
    recovery_assessment: Optional[Dict[str, Any]] = None
    execution_source: Literal["cloud_gemini", "edge_slm_offline_sync"] = Field(
        default="cloud_gemini"
    )
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    offline_created_at: Optional[datetime] = None

    model_config = ConfigDict(populate_by_name=True)


