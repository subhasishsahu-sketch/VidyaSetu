          ? InterventionOutput.fromJson(Map<String, dynamic>.from(json['intervention'] as Map))
          : null,
      recoveryPracticeQuestion: json['recovery_practice_question'] != null
          ? RecoveryPracticeQuestionModel.fromJson(
              Map<String, dynamic>.from(json['recovery_practice_question'] as Map))
          : null,
    );
  }
}

/// Payload when student submits recovery practice answer.
@immutable
class RecoverySubmitRequest {
  final String analysisId;
  final String practiceId;
  final String submittedAnswer;

  RecoverySubmitRequest({
    required this.analysisId,
    required this.practiceId,
    required String submittedAnswer,
  }) : submittedAnswer = submittedAnswer.trim().toUpperCase();

  Map<String, dynamic> toJson() => {
        'analysis_id': analysisId.toLowerCase(),
        'practice_id': practiceId,
        'submitted_answer': submittedAnswer,
        'selected_option': submittedAnswer,
      };

  factory RecoverySubmitRequest.fromJson(Map<String, dynamic> json) {
    final ans = (json['submitted_answer'] ?? json['selected_option'] ?? '').toString();
    return RecoverySubmitRequest(
      analysisId: (json['analysis_id'] ?? '').toString().toLowerCase(),
      practiceId: (json['practice_id'] ?? '').toString(),
      submittedAnswer: ans,
    );
  }
}

/// Response returned after grading recovery attempt.
@immutable
class RecoverySubmitResponse {
  final String analysisId;
  final bool isCorrect;
  final bool hasStudentImproved;
  final Map<String, double> updatedScores;
  final Map<String, dynamic> recommendedNextTask;

  const RecoverySubmitResponse({
    required this.analysisId,
    required this.isCorrect,
    required this.hasStudentImproved,
    required this.updatedScores,
    required this.recommendedNextTask,
  });

  Map<String, dynamic> toJson() => {
        'analysis_id': analysisId,
        'is_correct': isCorrect,
        'has_student_improved': hasStudentImproved,
        'updated_scores': updatedScores,
        'recommended_next_task': recommendedNextTask,
      };

  factory RecoverySubmitResponse.fromJson(Map<String, dynamic> json) {
    final rawScores = (json['updated_scores'] as Map?) ?? {};
    final scores = rawScores.map(
      (k, v) => MapEntry(k.toString(), ((v as num?) ?? 0.0).toDouble()),
    );
    final task = Map<String, dynamic>.from((json['recommended_next_task'] as Map?) ?? {});

    return RecoverySubmitResponse(
      analysisId: (json['analysis_id'] ?? '').toString().toLowerCase(),
      isCorrect: (json['is_correct'] as bool?) ?? false,
      hasStudentImproved: (json['has_student_improved'] as bool?) ?? false,
      updatedScores: scores,
      recommendedNextTask: task,
    );
  }
}
