  }

  factory ProbeResponseResult.fromJson(Map<String, dynamic> json) {
    return ProbeResponseResult(
      analysisId: (json['analysis_id'] ?? '').toString().toLowerCase(),
      status: (json['status'] ?? 'probe_required').toString(),
      confirmedHypothesis: json['confirmed_hypothesis']?.toString(),
      confidenceScore: (json['confidence_score'] as num?)?.toDouble(),
