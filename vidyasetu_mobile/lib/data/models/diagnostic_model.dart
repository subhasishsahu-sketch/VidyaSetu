/// Student question attempt payload supporting mobile telemetry aliases.
@immutable
class AttemptRequest {
  final String studentId;
  final String questionId;
  final String selectedOption;
  final double timeTakenSec;
  final int answerChangesCount;
  final double confidenceRating;
  final DateTime? offlineCreatedAt;

  AttemptRequest({
    required this.studentId,
    required this.questionId,
    required String selectedOption,
    double? timeTakenSec,
    double? timeTakenSeconds,
    int? answerChangesCount,
    int? answerChanges,
    double? confidenceRating,
    double? confidenceLevel,
    this.offlineCreatedAt,
  })  : selectedOption = selectedOption.trim().toUpperCase(),
        timeTakenSec = (timeTakenSec ?? timeTakenSeconds ?? 30.0).toDouble(),
        answerChangesCount = (answerChangesCount ?? answerChanges ?? 0).toInt(),
        confidenceRating = (confidenceRating ?? confidenceLevel ?? 50.0).toDouble();

  Map<String, dynamic> toJson() {
    final map = <String, dynamic>{
      'student_id': studentId.toLowerCase(),
      'question_id': questionId.toLowerCase(),
      'selected_option': selectedOption,
      'submitted_answer': selectedOption,
      'time_taken_sec': timeTakenSec,
      'time_taken_seconds': timeTakenSec,
      'answer_changes_count': answerChangesCount,
      'answer_changes': answerChangesCount,
      'confidence_rating': confidenceRating,
      'confidence_level': confidenceRating,
    };
    if (offlineCreatedAt != null) {
      map['offline_created_at'] = offlineCreatedAt!.toUtc().toIso8601String();
    }
    return map;
  }

  factory AttemptRequest.fromJson(Map<String, dynamic> json) {
    final opt = (json['selected_option'] ?? json['submitted_answer'] ?? '').toString();
    final time = (json['time_taken_sec'] ?? json['time_taken_seconds'] ?? 30.0) as num;
    final changes = (json['answer_changes_count'] ?? json['answer_changes'] ?? 0) as num;
    final conf = (json['confidence_rating'] ?? json['confidence_level'] ?? 50.0) as num;
    final offCreated = json['offline_created_at'] != null
        ? DateTime.parse(json['offline_created_at'] as String)
        : null;

    return AttemptRequest(
      studentId: (json['student_id'] ?? '').toString().toLowerCase(),
      questionId: (json['question_id'] ?? '').toString().toLowerCase(),
      selectedOption: opt,
      timeTakenSec: time.toDouble(),
      answerChangesCount: changes.toInt(),
      confidenceRating: conf.toDouble(),
      offlineCreatedAt: offCreated,
    );
  }
}

/// Response returned after processing initial attempt.
@immutable
class AttemptResponse {
  final String analysisId;
  final bool isCorrect;
  final String status; // 'passed' | 'probe_required'
  final List<CandidateHypothesis> candidateHypotheses;
  final Map<String, dynamic>? selectedProbe;

  const AttemptResponse({
    required this.analysisId,
    required this.isCorrect,
    required this.status,
    this.candidateHypotheses = const [],
    this.selectedProbe,
  });

  Map<String, dynamic> toJson() {
    return {
      'analysis_id': analysisId,
      'is_correct': isCorrect,
      'status': status,
      'candidate_hypotheses': candidateHypotheses.map((h) => h.toJson()).toList(),
      'selected_probe': selectedProbe,
    };
  }

  factory AttemptResponse.fromJson(Map<String, dynamic> json) {
    final hyps = (json['candidate_hypotheses'] as List?)
            ?.map((h) => CandidateHypothesis.fromJson(Map<String, dynamic>.from(h as Map)))
            .toList() ??
        [];
    return AttemptResponse(
      analysisId: (json['analysis_id'] ?? '').toString().toLowerCase(),
      isCorrect: (json['is_correct'] as bool?) ?? false,
      status: (json['status'] ?? 'passed').toString(),
      candidateHypotheses: hyps,
      selectedProbe: json['selected_probe'] != null
          ? Map<String, dynamic>.from(json['selected_probe'] as Map)
          : null,
    );
  }
}

/// Payload when student answers a diagnostic probe.
@immutable
class ProbeResponseRequest {
  final String analysisId;
  final String probeType;
  final String submittedAnswer;
  final double timeTakenSec;

  ProbeResponseRequest({
    required this.analysisId,
    required this.probeType,
    required String submittedAnswer,
    double? timeTakenSec,
    double? probeTimeTakenSec,
    double? timeTakenSeconds,
  })  : submittedAnswer = submittedAnswer.trim().toUpperCase(),
        timeTakenSec = (timeTakenSec ?? probeTimeTakenSec ?? timeTakenSeconds ?? 20.0).toDouble();

  Map<String, dynamic> toJson() {
    return {
      'analysis_id': analysisId.toLowerCase(),
      'probe_type': probeType,
      'submitted_answer': submittedAnswer,
      'probe_submitted_answer': submittedAnswer,
      'selected_option': submittedAnswer,
      'time_taken_sec': timeTakenSec,
      'probe_time_taken_sec': timeTakenSec,
    };
  }

  factory ProbeResponseRequest.fromJson(Map<String, dynamic> json) {
    final ans = (json['submitted_answer'] ??
            json['probe_submitted_answer'] ??
            json['selected_option'] ??
            '')
        .toString();
    final time = (json['time_taken_sec'] ??
            json['probe_time_taken_sec'] ??
            json['time_taken_seconds'] ??
            20.0) as num;

    return ProbeResponseRequest(
      analysisId: (json['analysis_id'] ?? '').toString().toLowerCase(),
      probeType: (json['probe_type'] ?? '').toString(),
      submittedAnswer: ans,
      timeTakenSec: time.toDouble(),
    );
  }
}

