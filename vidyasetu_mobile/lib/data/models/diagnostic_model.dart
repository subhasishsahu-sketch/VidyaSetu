/// Categorical 7-parameter behavioral snapshot.
@immutable
class StudentParametersSnapshot {
  final String timeTaken; // 'High' | 'Normal' | 'Low'
  final String confidenceLevel; // 'High' | 'Normal' | 'Low'
  final String answerChanges; // 'Frequent' | 'Occasional' | 'None'
  final String languagePreference; // 'Odia' | 'English'
  final String conceptUnderstanding; // 'Understood' | 'Weak'
  final String previousPerformance; // 'Strong' | 'Weak'
  final String englishComprehension; // 'Strong' | 'Weak'

  const StudentParametersSnapshot({
    this.timeTaken = 'Normal',
    this.confidenceLevel = 'Normal',
    this.answerChanges = 'None',
    this.languagePreference = 'Odia',
    this.conceptUnderstanding = 'Understood',
    this.previousPerformance = 'Strong',
    this.englishComprehension = 'Strong',
  });

  Map<String, dynamic> toJson() {
    return {
      'time_taken': timeTaken,
      'confidence_level': confidenceLevel,
      'answer_changes': answerChanges,
      'language_preference': languagePreference,
      'concept_understanding': conceptUnderstanding,
      'previous_performance': previousPerformance,
      'english_comprehension': englishComprehension,
    };
  }

  factory StudentParametersSnapshot.fromJson(Map<String, dynamic> json) {
    return StudentParametersSnapshot(
      timeTaken: (json['time_taken'] ?? 'Normal').toString(),
      confidenceLevel: (json['confidence_level'] ?? 'Normal').toString(),
      answerChanges: (json['answer_changes'] ?? 'None').toString(),
      languagePreference: (json['language_preference'] ?? 'Odia').toString(),
      conceptUnderstanding: (json['concept_understanding'] ?? 'Understood').toString(),
      previousPerformance: (json['previous_performance'] ?? 'Strong').toString(),
      englishComprehension: (json['english_comprehension'] ?? 'Strong').toString(),
    );
  }
}

